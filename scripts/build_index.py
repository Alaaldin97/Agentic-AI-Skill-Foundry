#!/usr/bin/env python3
"""Rebuild INDEX.md and docs/gallery.html from whatever is in skills/.

    python scripts/build_index.py

Runs automatically on every merge to main, so the catalog is never stale.
"""
from __future__ import annotations

import datetime
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
INDEX = ROOT / "INDEX.md"
GALLERY = ROOT / "docs" / "gallery.html"

SHAPES = {
    "instructions": ("Instructions only", "#6b7fd7"),
    "method": ("Enforces a method", "#8b5cf6"),
    "scripts": ("Ships scripts", "#0f9d58"),
    "knowledge": ("Ships knowledge", "#d97706"),
    "runtime": ("Ships a runtime", "#b11f4b"),
}

sys.path.insert(0, str(ROOT / "scripts"))
from validate_skill import parse_frontmatter  # noqa: E402


def load(path: pathlib.Path) -> dict | None:
    skill_md = path / "SKILL.md"
    if not skill_md.exists():
        return None

    fm = parse_frontmatter(skill_md.read_text(encoding="utf-8")) or {}
    meta_path = path / "meta.yml"
    meta = {}
    if meta_path.exists():
        meta = parse_frontmatter("---\n" + meta_path.read_text(encoding="utf-8") + "\n---\n") or {}

    desc = re.sub(r"\s+", " ", fm.get("description", "")).strip()
    trigger, _, dormant = desc.partition("Does NOT fire on:")

    return {
        "name": fm.get("name", path.name),
        "folder": path.name,
        "description": desc,
        "trigger": trigger.strip(),
        "dormant": dormant.strip(),
        "author": meta.get("author", "unknown"),
        "github": meta.get("github", ""),
        "category": (meta.get("category") or "other").strip(),
        "shape": (meta.get("shape") or "instructions").strip(),
        "tested_on": meta.get("tested_on", ""),
        "date": meta.get("date", ""),
        "has_scripts": (path / "scripts").is_dir(),
        "has_resources": (path / "resources").is_dir(),
    }


def collect() -> list[dict]:
    if not SKILLS.is_dir():
        return []
    out = []
    for p in sorted(SKILLS.iterdir()):
        if p.is_dir() and not p.name.startswith("_"):
            s = load(p)
            if s:
                out.append(s)
    return out


def write_index(skills: list[dict]) -> None:
    today = datetime.date.today().isoformat()
    L: list[str] = []
    L.append("# The Skill Foundry — catalog\n")
    L.append(f"*{len(skills)} skill{'s' if len(skills) != 1 else ''} · rebuilt {today}*\n")
    L.append("> Auto-generated by `scripts/build_index.py`. Do not edit by hand —")
    L.append("> your changes will be overwritten on the next merge.\n")

    if not skills:
        L.append("\nNothing here yet. **[Be the first →](CONTRIBUTING.md)**\n")
        INDEX.write_text("\n".join(L), encoding="utf-8")
        return

    by_cat: dict[str, list[dict]] = {}
    for s in skills:
        by_cat.setdefault(s["category"], []).append(s)

    L.append("\n## At a glance\n")
    L.append("| Skill | What it does | Shape | Author |")
    L.append("|---|---|---|---|")
    for s in skills:
        shape_label = SHAPES.get(s["shape"], ("Instructions only", ""))[0]
        short = s["trigger"][:110] + ("…" if len(s["trigger"]) > 110 else "")
        who = f"[@{s['github']}](https://github.com/{s['github']})" if s["github"] else s["author"]
        L.append(f"| **[{s['name']}](skills/{s['folder']}/)** | {short} | {shape_label} | {who} |")

    L.append("\n---\n")

    for cat in sorted(by_cat):
        L.append(f"\n## {cat.replace('-', ' ').title()}\n")
        for s in by_cat[cat]:
            L.append(f"### [{s['name']}](skills/{s['folder']}/)\n")
            L.append(f"{s['trigger']}\n")
            if s["dormant"]:
                L.append(f"> **Does not fire on:** {s['dormant']}\n")
            bits = []
            if s["has_scripts"]:
                bits.append("ships `scripts/`")
            if s["has_resources"]:
                bits.append("ships `resources/`")
            if s["tested_on"]:
                bits.append(f"tested on {s['tested_on']}")
            if bits:
                L.append(f"*{' · '.join(bits)}*\n")
            L.append(
                f"[SKILL.md](skills/{s['folder']}/SKILL.md) · "
                f"[Evidence](skills/{s['folder']}/EVIDENCE.md)\n"
            )

    L.append("\n---\n")
    L.append("**[← Back to README](README.md)** · **[Add your own →](CONTRIBUTING.md)**\n")
    INDEX.write_text("\n".join(L), encoding="utf-8")


def write_gallery(skills: list[dict]) -> None:
    today = datetime.date.today().isoformat()
    cards = []
    for s in skills:
        label, colour = SHAPES.get(s["shape"], ("Instructions only", "#6b7fd7"))
        tags = []
        if s["has_scripts"]:
            tags.append("scripts")
        if s["has_resources"]:
            tags.append("resources")
        tag_html = "".join(f'<span class="tag">{html.escape(t)}</span>' for t in tags)
        dormant_html = (
            f'<p class="dormant"><b>Does not fire on:</b> {html.escape(s["dormant"])}</p>'
            if s["dormant"] else ""
        )
        who = html.escape(s["author"])
        if s["github"]:
            who = f'<a href="https://github.com/{html.escape(s["github"])}">@{html.escape(s["github"])}</a>'
        cards.append(f"""
      <article class="card" data-cat="{html.escape(s['category'])}" data-name="{html.escape(s['name'].lower())} {html.escape(s['trigger'].lower())}">
        <span class="shape" style="--c:{colour}">{label}</span>
        <h3><a href="../skills/{html.escape(s['folder'])}/SKILL.md">{html.escape(s['name'])}</a></h3>
        <p class="desc">{html.escape(s['trigger'])}</p>
        {dormant_html}
        <div class="tags">{tag_html}</div>
        <footer>
          <span>{who}</span>
          <a class="ev" href="../skills/{html.escape(s['folder'])}/EVIDENCE.md">See it run →</a>
        </footer>
      </article>""")

    cats = sorted({s["category"] for s in skills})
    chips = "".join(
        f'<button class="chip" data-f="{html.escape(c)}">{html.escape(c.replace("-", " "))}</button>'
        for c in cats
    )

    empty = "" if skills else """
      <div class="empty">
        <h2>Nothing forged yet</h2>
        <p>Be the first — see <a href="../CONTRIBUTING.md">CONTRIBUTING.md</a>.</p>
      </div>"""

