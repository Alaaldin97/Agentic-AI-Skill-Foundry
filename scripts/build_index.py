def main() -> int:
    skills = collect()
    write_index(skills)
    write_gallery(skills)
    print(f"indexed {len(skills)} skill(s)")
    print(f"  {INDEX.relative_to(ROOT)}")
    print(f"  {GALLERY.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
